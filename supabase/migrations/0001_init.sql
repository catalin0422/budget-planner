CREATE INDEX IF NOT EXISTS idx_snapshot_balances_snapshot
  ON snapshot_balances (snapshot_id);

-- ---------------------------------------------------------------------------
-- Securitate
-- ---------------------------------------------------------------------------
-- Autentificarea aplicatiei e Clerk, iar accesul la baza se face exclusiv
-- server-side, printr-o conexiune Postgres directa cu utilizatorul `postgres`
-- (care oricum ignora RLS). Rolurile `anon` si `authenticated` -- adica cine
-- ajunge prin Data API-ul public al Supabase, cu cheia publishable -- nu au ce
-- cauta aici.
--
-- Activam RLS FARA nicio policy: fara policy, RLS respinge tot. Plus revocam
-- explicit grant-urile, ca tabelele sa nu fie expuse nici daca Data API-ul e
-- pornit din dashboard. Cele doua impreuna inseamna ca un URL public cu cheia
-- anon nu poate citi nimic.
ALTER TABLE accounts          ENABLE ROW LEVEL SECURITY;
ALTER TABLE snapshots         ENABLE ROW LEVEL SECURITY;
ALTER TABLE snapshot_balances ENABLE ROW LEVEL SECURITY;
ALTER TABLE recurring         ENABLE ROW LEVEL SECURITY;
ALTER TABLE planned           ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_settings      ENABLE ROW LEVEL SECURITY;
ALTER TABLE trip_settings     ENABLE ROW LEVEL SECURITY;

-- Rolurile `anon` si `authenticated` exista doar pe Supabase. Pe un Postgres
-- obisnuit (ex: container local de test) REVOKE ar da eroare si ar opri
-- migratia, asa ca revocam doar rolurile care chiar exista.
DO $$
DECLARE
  r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format(
        'REVOKE ALL ON accounts, snapshots, snapshot_balances, recurring, ' ||
        'planned, app_settings, trip_settings FROM %I', r
      );
    END IF;
  END LOOP;
END
$$;
